def extract_geocoded_points():
    with open(INPUT_ATLAS, "r", encoding="utf-8") as f:
        html = f.read()
    m = re.search(r"const\s+PTS\s*=\s*(\[.*?\]);", html, re.S)
    if not m:
        m = re.search(r"PTS\s*=\s*(\[.*?\]);", html, re.S)
    if not m:
        raise RuntimeError("Could not locate PTS array in Atlas_V3.html")
    pts = json.loads(m.group(1))
    for p in pts:
        p["Normalized_Sector"] = normalize_sector(p.get("cat", ""), p.get("name", ""))
    return pts


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # 1. Read master CSV
    with open(INPUT_CSV, "r", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        fieldnames = list(reader.fieldnames)
        rows = list(reader)

    # 2. Enrich with Normalized_Sector & write enriched CSV
    enriched_fields = fieldnames + ["Normalized_Sector"]
    for r in rows:
        r["Normalized_Sector"] = normalize_sector(
            r.get("Main_Category", ""), r.get("Business_Name", "")
        )

    with open(OUTPUT_CSV, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=enriched_fields)
        writer.writeheader()
        writer.writerows(rows)

    # 3. Compute aggregations
    total_businesses = len(rows)
    markaz_counts = Counter(r["Markaz"] for r in rows)
    sector_counts = Counter(r["Normalized_Sector"] for r in rows)
    localities = set(r["City_Village"].strip() for r in rows if r.get("City_Village", "").strip())

    all_markaz = [m for m, _ in markaz_counts.most_common()]
    all_sectors = [s for s, _ in sector_counts.most_common()]

    # High confidence counts per markaz
    markaz_high_conf = Counter(
        r["Markaz"] for r in rows if (r.get("Confidence") or "").strip().lower() == "high"
    )

    # Matrix counts: markaz -> sector -> count
    ms_counts = defaultdict(Counter)
    for r in rows:
        ms_counts[r["Markaz"]][r["Normalized_Sector"]] += 1

    # Governorate-wide density per 100k pop for each sector
    total_pop = sum(MARKAZ_META[m]["population_est"] for m in all_markaz if m in MARKAZ_META)
    gov_sector_density = {
        s: (sector_counts[s] / total_pop) * 100000.0 for s in all_sectors
    }

    # Build matrix with saturation & opportunity
    matrix = {}
    sector_sat_accum = defaultdict(list)
    sector_opp_accum = defaultdict(list)

    for m in all_markaz:
        pop = MARKAZ_META.get(m, {"population_est": 200000})["population_est"]
        matrix[m] = {}
        for s in all_sectors:
            cnt = ms_counts[m][s]
            local_density = (cnt / pop) * 100000.0
            bench = max(gov_sector_density[s], 0.25)
            # Saturation: 0..95 based on local_density relative to governorate benchmark
            ratio = local_density / bench
            sat = int(round(min(95, max(5, 48 * math.log1p(ratio * 1.4)))))
            if cnt == 0:
                sat = 5

            # Opportunity: inverse of saturation + sector growth boost + pop factor
            pop_factor = min(8, int(round((pop / 500000.0) * 8)))
            boost = SECTOR_GROWTH_BOOST.get(s, 6)
            opp = int(round(min(96, max(18, (100 - sat) * 0.78 + boost + pop_factor))))

            matrix[m][s] = {
                "count": cnt,
                "saturation": sat,
                "opportunity": opp,
            }
            sector_sat_accum[s].append(sat)
            sector_opp_accum[s].append(opp)

    # Build markaz_info
    markaz_info = []
    gov_density = (total_businesses / total_pop) * 100000.0
    for m in all_markaz:
        meta = MARKAZ_META.get(m, {"lat": 31.1107, "lng": 30.9388, "population_est": 200000})
        cnt = markaz_counts[m]
        pop = meta["population_est"]
        local_dens = (cnt / pop) * 100000.0
        sat_idx = int(round(min(92, max(18, 45 * math.log1p((local_dens / gov_density) * 1.35)))))
        opp_score = int(round(min(92, max(35, (100 - sat_idx) * 0.8 + min(12, pop / 45000.0)))))

        top_sectors = [
            {"sector": s, "count": c}
            for s, c in ms_counts[m].most_common(5)
        ]

        markaz_info.append({
            "name": m,
            "lat": meta["lat"],
            "lng": meta["lng"],
            "population_est": pop,
            "business_count": cnt,
            "high_conf_count": markaz_high_conf[m],
            "saturation_index": sat_idx,
            "opportunity_score": opp_score,
            "top_sectors": top_sectors,
        })

    # Build sectors_summary
    sectors_summary = []
    for s in all_sectors:
        cnt = sector_counts[s]
        pct = round((cnt / total_businesses) * 100.0, 1)
        avg_sat = int(round(sum(sector_sat_accum[s]) / len(sector_sat_accum[s])))
        avg_opp = int(round(sum(sector_opp_accum[s]) / len(sector_opp_accum[s])))

        if cnt >= 120:
            cov_status = "مكتمل"
        elif cnt >= 40:
            cov_status = "ناقص البيانات"
        else:
            cov_status = "فرصة جديدة"

        sectors_summary.append({
            "sector": s,
            "count": cnt,
            "pct": pct,
            "avg_saturation": avg_sat,
            "opportunity_score": avg_opp,
            "coverage_status": cov_status,
        })

    # 4. Activities catalog
    activities_catalog = build_activities_catalog(sector_counts)

    # 5. Geocoded points from Atlas_V3.html
    geocoded_points = extract_geocoded_points()

    # 6. Compact businesses array
    businesses = [
        [
            (r.get("Business_Name") or "").strip(),
            r["Normalized_Sector"],
            (r.get("Main_Category") or "").strip(),
            (r.get("Markaz") or "").strip(),
            (r.get("City_Village") or "").strip(),
            (r.get("Street") or "").strip(),
            (r.get("Phone") or "").strip(),
            (r.get("Rating") or "").strip(),
            (r.get("Confidence") or "").strip() or "Low",
        ]
        for r in rows
    ]

    platform_data = {
        "meta": {
            "title": "منصة كفر الشيخ الذكية لدراسة السوق والأنشطة التجارية — V4",
            "total_businesses": total_businesses,
            "total_markaz": len(all_markaz),
            "total_localities": len(localities),
            "total_sectors": len(all_sectors),
            "total_activities_catalog": len(activities_catalog),
            "geocoded_points": len(geocoded_points),
        },
        "markaz_info": markaz_info,
        "sectors_summary": sectors_summary,
        "matrix": matrix,
        "activities_catalog": activities_catalog,
        "geocoded_points": geocoded_points,
        "businesses": businesses,
    }

    # Write compact JSON
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(platform_data, f, ensure_ascii=False, separators=(",", ":"))

    # Print verification summary
    print("=== BUILD COMPLETE ===")
    print(f"Total businesses: {total_businesses}")
    print(f"Total markaz: {len(all_markaz)}")
    print(f"Total localities: {len(localities)}")
    print(f"Total sectors: {len(all_sectors)}")
    print(f"Total activities catalog: {len(activities_catalog)}")
    print(f"Geocoded points: {len(geocoded_points)}")
    print(f"Output CSV size: {os.path.getsize(OUTPUT_CSV):,} bytes")
    print(f"Output JSON size: {os.path.getsize(OUTPUT_JSON):,} bytes")
    print("\nSector distribution:")
    for s_obj in sectors_summary:
        print(f"  - {s_obj['sector']}: {s_obj['count']} ({s_obj['pct']}%) | Sat: {s_obj['avg_saturation']} | Opp: {s_obj['opportunity_score']} | {s_obj['coverage_status']}")


